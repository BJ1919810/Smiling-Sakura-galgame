def main() -> int:
    ap = argparse.ArgumentParser(description="第一章样板精修")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    text = SRC.read_text(encoding="utf-8")
    lines = text.split("\n")

    # 先锁定第一章范围（只在这里动）
    ch1 = next(i for i, L in enumerate(lines) if L.startswith("# 第 1 章"))
    ch2 = next(i for i, L in enumerate(lines) if L.startswith("# 第 2 章"))
    head = "\n".join(lines[:ch1])
    body = "\n".join(lines[ch1:ch2])
    tail = "\n".join(lines[ch2:])

    print(f"第一章范围：L{ch1 + 1}~L{ch2}（{ch2 - ch1} 行）\n")

    ok = True
    for i, (old, new, note) in enumerate(EDITS, 1):
        n = body.count(old)
        flag = "✓" if n == 1 else "✗"
        if n != 1:
            ok = False
        print(f"  {flag} [{i:2d}] {note}")
        if n != 1:
            print(f"        匹配 {n} 次（期望 1）—— 原文可能已变动")
        if not args.dry_run and n == 1:
            body = body.replace(old, new)

    if not ok:
        print("\n✗ 有改动未能唯一匹配，已中止（文件未写）。")
        return 1

    if args.dry_run:
        print(f"\n（--dry-run）共 {len(EDITS)} 处，全部唯一匹配，可执行。")
        return 0

    BACKUP_DIR.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    backup = BACKUP_DIR / f"笑樱_galgame台本_第一章精修前_{stamp}.md"
    shutil.copy2(SRC, backup)
    SRC.write_text(head + "\n" + body + "\n" + tail, encoding="utf-8")
    print(f"\n✓ 已备份 → {backup.name}")
    print(f"✓ 已写回，共改 {len(EDITS)} 处")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
