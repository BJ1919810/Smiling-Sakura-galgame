/**
 * 台词 / 括注情绪判别 —— 「雀跃」演出的触发器
 *
 * 需求（主人 2026-09-12）：角色即将说**正向高情绪**的话时，立绘快速向上跳一下。
 * 正向高情绪 ＝ 震惊 / 激动 / 欢愉；**愤怒、生气不算**。
 *
 * ★ 为什么判「立绘括注（pose）」而不是判台词词面 ——
 *   实测（429 条有主台词）：词面匹配会大量误判。例如含「笑」的 57 条里，
 *   绝大多数是在**讨论**笑（「我在练笑」「你不喜欢笑吗」），角色本人并非欢愉；
 *   「叫」命中的 6 条全是「叫什么名字」；「喜」「欢」命中的是「**不**喜欢」。
 *   而立绘括注是作者亲手写下的**当下心情**，台本自己都会写
 *   「她面无表情，但眼睛微微睁大了一点——那是她表达惊讶的」。
 *   所以：括注命中 → 演出触发；台本侧想加一处雀跃，只需在括注里写上对应词。
 *
 * 纯函数、无副作用：Director 与单测共用同一份词表。
 */

/**
 * 正向高情绪（震惊 / 激动 / 欢愉）。
 * 设计约束：
 * - 「弯」必须绑定「眼」——否则阳太的「弯腰撑膝」会误报；
 * - 不收录裸「笑 / 微笑」——樱「从来不会笑」，而九条院的「完美微笑」是**伪装面**，
 *   在那上面蹦一下会毁掉反派感。
 */
const POSITIVE =
  /亮|睁大|瞪大|眼睛.{0,4}弯|弯.{0,4}眼|意外|惊|嬉|雀跃|蹦|兴奋|激动|欢呼|惊喜/;

/** 愤怒 / 生气 / 敌意 —— 主人指定**不算**正向高情绪，命中即一票否决 */
const NEGATIVE =
  /怒|生气|恼|沉下|阴沉|冷冷|板起|咬牙|皱眉|不耐|压低|铁青|瞪眼/;

/**
 * 是否「正向高情绪」。
 * @param text 立绘括注（pose）或任意待判文本
 */
export function isPositiveHighEmotion(text: string): boolean {
  if (!text) return false;
  // 先查否定：一条括注里同时出现「沉下脸」和「亮」时，以否定为准（怒极反笑不算欢愉）
  if (NEGATIVE.test(text)) return false;
  return POSITIVE.test(text);
}
